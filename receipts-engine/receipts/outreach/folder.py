"""out/outreach/ (BUILD_SPEC 9.4): sequences, Priority A packs, first messages, validator report."""
from __future__ import annotations

import csv
import json
import shutil
from importlib import resources
from pathlib import Path

from receipts.pipeline.s8_messages import MSG_CHANNELS, SEGMENTS, message_channel

README = """# Outreach folder

Generated by `receipts export`. Nothing in here has been sent.

- `sequences/<segment>/<channel>/sequence.md`: the template for steps 1-3, the variables it uses and the timing
  (days after step 1: {days}).
- `priority_a/<lead_id>.md`: the three rendered messages for the lead's best channel and its backup channel,
  with the source URL of the fact used in the hook. Check the hook link before sending.
- `all_first_messages.csv`: step 1 for every exported lead.
- `validator_report.csv`: every validator result for every drafted message.

LinkedIn, Instagram, X and contact forms are **assisted send**: a person sends them by hand from their own
account; the engine never automates them. Every message carries the sender's name, role and postal address
(LinkedIn: name and role) and an opt-out line. Honour every STOP immediately.
"""

VARIABLES = ["creator_first_name", "hook", "signal_phrase", "item_word", "offer_line", "sender.name", "sender.role",
             "sender.postal_address", "tracked_link", "opt_out_line", "title", "subject_title", "second_observation",
             "date_words", "hook_short", "linkedin_opt_out"]


def write_outreach_folder(db, s, d: Path, rows: list[dict]) -> Path:
    if d.exists():
        shutil.rmtree(d)
    d.mkdir(parents=True)
    (d / "README.md").write_text(README.format(days=", ".join(str(x) for x in s.follow_up_days)))
    root = resources.files("receipts.outreach").joinpath("templates")
    for seg in SEGMENTS:
        for ch in MSG_CHANNELS:
            out = d / "sequences" / seg / ch
            out.mkdir(parents=True)
            parts = [f"# Sequence: {seg} / {ch}\n",
                     f"Timing: step 1 on day {s.follow_up_days[0]}, step 2 on day {s.follow_up_days[1]}, "
                     f"step 3 on day {s.follow_up_days[2]}. A STOP or negative reply cancels the remaining steps.\n",
                     "Send mode: " + ("assisted (a person sends by hand)" if ch in ("linkedin", "form") else
                                      "automatable (email)") + "\n"]
            for step in (1, 2, 3):
                text = root.joinpath(seg, ch, f"step{step}.j2").read_text()
                used = [v for v in VARIABLES if "{{ " + v in text or "{{ " + v.split(".")[0] in text]
                parts.append(f"## Step {step}\n\nVariables: {', '.join(used)}\n\n```\n{text.strip()}\n```\n")
            (out / "sequence.md").write_text("\n".join(parts))
    pa = d / "priority_a"
    pa.mkdir()
    for r in rows:
        if r["priority"] != "A":
            continue
        lines = [f"# {r['lead_id']} {r['creator_name']} ({r['creator_segment']}, {r['country_iso2']}, score {r['lead_score']})\n",
                 f"Hook: {r['personalization_hook']}\n"]
        for role, typ in (("Best", r["best_type"]), ("Backup", r["backup_type"])):
            ch = message_channel(typ)
            msgs = db.fetch_all("SELECT * FROM messages WHERE creator_key=? AND channel=? ORDER BY step",
                                (r["creator_key"], ch))
            value = r["channel_handle_or_url"] if role == "Best" else r["backup_value"]
            lines.append(f"## {role} channel: {typ} -> {value} (message template: {ch})\n")
            for m in msgs:
                lines.append(f"### Step {m['step']} (day {s.follow_up_days[m['step'] - 1]})"
                             + (" [assisted send]" if m["assisted_send"] else "") + "\n")
                if m["subject"]:
                    lines.append(f"Subject: {m['subject']}\n")
                lines.append(f"```\n{m['body']}\n```\nHook source: {m['hook_source_url']}\n")
        (pa / f"{r['lead_id']}.md").write_text("\n".join(lines))
    with (d / "all_first_messages.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["lead_id", "channel", "subject", "body", "validated"])
        for r in rows:
            ch = message_channel(r["best_type"])
            m = db.fetch_one("SELECT * FROM messages WHERE creator_key=? AND channel=? AND step=1", (r["creator_key"], ch))
            if m:
                w.writerow([r["lead_id"], ch, m["subject"] or "", m["body"], m["validated"]])
    with (d / "validator_report.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["lead_id", "channel", "step", "rule", "pass", "note"])
        for r in rows:
            for m in db.fetch_all("SELECT * FROM messages WHERE creator_key=? ORDER BY channel, step", (r["creator_key"],)):
                for v in json.loads(m["validator_report"] or "[]"):
                    w.writerow([r["lead_id"], m["channel"], m["step"], v["rule"], int(v["pass"]), v["note"]])
    return d
