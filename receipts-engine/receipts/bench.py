"""`receipts bench`: synthetic replay benchmark (labelled synthetic, never live). Separate DB and fixtures."""
from __future__ import annotations

import asyncio
import os
import resource
import shutil
import sys
import time
from datetime import UTC, datetime
from pathlib import Path


def build_bench_world(fx: Path, rows: int, dup_fraction: float = 0.05):
    sys.path.insert(0, str(Path.cwd()))
    from scripts.make_synthetic import SynthCreator, build_world, input_ref

    places = {"US": "Austin, Texas", "GB": "London, England", "CA": "Toronto, Canada", "AU": "Sydney, Australia",
              "IE": "Dublin, Ireland", "NZ": "Auckland, New Zealand", "SG": "Singapore"}
    cc = list(places)
    n_dup = int(rows * dup_fraction)
    base = rows - n_dup
    world, refs = [], []
    for i in range(1, base + 1):
        country = cc[i % len(cc)]
        kind = ("youtube", "podcast", "expert")[i % 3]
        c = SynthCreator(n=i, kind="podcast" if kind == "podcast" else "youtube", country=country, place=places[country],
                         expert=kind == "expert", active=i % 17 != 0, english=i % 23 != 0)
        world.append(c)
        refs.append(input_ref(c))
    # injected duplicates: the same creator's podcast feed sharing the YouTube creator's website
    yts = [c for c in world if c.kind == "youtube" and not c.expert][:n_dup]
    dups = [SynthCreator(n=c.n, kind="podcast", country=c.country, place=c.place) for c in yts]
    world += dups
    refs += [input_ref(c) for c in dups]
    build_world(fx, world, datetime.now(UTC))
    return refs, len(dups)


def run_bench(rows: int, settings) -> dict:
    out = Path(settings.bench.db_path).parent
    if out.exists():
        shutil.rmtree(out)
    fx = out / "fixtures"
    t0 = time.perf_counter()
    refs, injected = build_bench_world(fx, rows)
    t_build = time.perf_counter() - t0
    inp = out / "bench_input.csv"
    inp.write_text("url\n" + "\n".join(refs) + "\n")
    os.environ.update({"FIXTURE_MODE": "1", "RECEIPTS_DB": settings.bench.db_path, "RECEIPTS_OUT": str(out),
                       "RECEIPTS_FIXTURES": str(fx)})
    from receipts.config import get_settings
    from receipts.db import init_db
    from receipts.pipeline.runner import run_pipeline

    get_settings.cache_clear()
    t1 = time.perf_counter()
    summary = asyncio.run(run_pipeline(str(inp), target=10**9, resume=False, kind="bench", llm=None))
    t_run = time.perf_counter() - t1
    db = init_db(get_settings().db_path)
    rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    peak_mb = rss / (1024 * 1024) if sys.platform == "darwin" else rss / 1024
    dupes = {
        "creators_sharing_an_identity": db.scalar(
            "SELECT COUNT(*) FROM (SELECT platform, platform_id FROM identities GROUP BY 1, 2 "
            "HAVING COUNT(DISTINCT creator_key) > 1)") or 0,
        "creators_sharing_primary_id": db.scalar(
            "SELECT COUNT(*) - COUNT(DISTINCT primary_id) FROM creators WHERE primary_id IS NOT NULL") or 0,
        "leads_per_creator_over_1": db.scalar("SELECT COUNT(*) - COUNT(DISTINCT creator_key) FROM leads") or 0,
    }
    res = {
        "label": "SYNTHETIC REPLAY (not live data)", "rows": len(refs), "injected_duplicates": injected,
        "dupes_removed": summary.dupes_removed, "duplicates_remaining": sum(dupes.values()), "dupe_detail": dupes,
        "qualified": summary.qualified_total, "rejected": summary.rejected, "status": summary.status,
        "build_seconds": round(t_build, 1), "run_seconds": round(t_run, 1),
        "candidates_per_second": round(len(refs) / t_run, 1) if t_run else 0, "peak_rss_mb": round(peak_mb, 1),
        "reject_reasons": summary.reasons,
    }
    db.close()
    return res


def write_bench_report(res: dict, path: Path) -> Path:
    lines = ["# Bench report", "", f"**{res['label']}**: generated by `receipts bench`; every creator is synthetic "
             "(`.test` domains, `data_origin=synthetic`). This measures engine throughput and dedupe, not live API speed "
             "(live runs are bounded by YouTube quota and per-host politeness delays).", "",
             "| Metric | Value |", "|---|---|"]
    for k in ("rows", "injected_duplicates", "dupes_removed", "duplicates_remaining", "qualified", "rejected", "status",
              "build_seconds", "run_seconds", "candidates_per_second", "peak_rss_mb"):
        lines.append(f"| {k} | {res[k]} |")
    lines += ["", f"Duplicate detail: {res['dupe_detail']}", f"Reject reasons: {res['reject_reasons']}",
              f"Generated {datetime.now(UTC).strftime('%Y-%m-%d %H:%M UTC')}."]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path
